# Purpose: isolated native IP/project generation and offline PDS stage execution.
# The optional bitstream stage creates only a volatile configuration image; this
# script performs no hardware access, programming, Flash/eFuse or system change.
param(
 [string]$PdsHome='E:/PDS_Pangu/PDS_2022.2-SP6.4',
 [string]$LicenseFile='',
 [switch]$GenerateIps,
 [ValidateSet('compile','synthesize','dev_map','pnr','report_timing','gen_bit_stream')]
 [string]$Stage='compile'
)
$ErrorActionPreference='Stop'
$taskFpga=Split-Path $PSScriptRoot -Parent
$taskRoot=Join-Path $taskFpga 'build/mini_camera_diag'
$taskRun=Join-Path $taskRoot ('native_'+(Get-Date -Format 'yyyyMMdd_HHmmss_fff'))
$taskImpl=Join-Path $taskRoot 'implementation'
$taskConstraints=Join-Path $taskFpga 'constraints/mini_camera_diag'
$taskProject=Join-Path $taskFpga 'project/mini_camera_diag/mini_camera_diag.pds'
New-Item -ItemType Directory -Path $taskRun,$taskImpl,$taskConstraints -Force | Out-Null

# Purpose: copy only relevant established board pin definitions, translating port
# names without altering the main project. CAM1 pins are from the J10 review report.
$taskRename=@{clk_27m='sys_clk';ref_clk_p='clk_p';ref_clk_n='clk_n';reset_n='rst_in'}
$taskPins=[Collections.Generic.List[string]]::new()
$taskPins.Add('# Generated by build_mini_camera_diag.ps1; MINI J10/CAM1 only. Electrical sign-off pending.')
foreach($taskLine in Get-Content (Join-Path $taskFpga 'constraints/board_pins.fdc')) {
 if($taskLine -match '^define_attribute \{p:([^}]+)\}') {
  $taskPort=$Matches[1]
  if($taskRename.ContainsKey($taskPort)) {
   $taskPins.Add($taskLine.Replace('{p:'+$taskPort+'}','{p:'+$taskRename[$taskPort]+'}'))
  } elseif($taskPort.StartsWith('hdmi_')) { $taskPins.Add($taskLine.Replace('hdmi_','tmds_')) }
 }
}
$taskCam=@(
 @('camera_clk_0','L22','INPUT'),@('camera_vsync_0','L23','INPUT'),
 @('camera_href_0','T25','INPUT'),@('camera_data_0[0]','M24','INPUT'),
 @('camera_data_0[1]','R22','INPUT'),@('camera_data_0[2]','K26','INPUT'),
 @('camera_data_0[3]','K25','INPUT'),@('camera_data_0[4]','M25','INPUT'),
 @('camera_data_0[5]','N19','INPUT'),@('camera_data_0[6]','T24','INPUT'),
 @('camera_data_0[7]','R21','INPUT'),@('SCL_0','P19','INOUT'),
 @('SDA_0','R20','INOUT'),@('cam_rst_0','T22','OUTPUT'),
 @('cam_led0','A20','OUTPUT'),@('cam_led1','C19','OUTPUT'),
 @('heart_beat_led','C18','OUTPUT')
)
foreach($taskPin in $taskCam) {
 $taskPort=$taskPin[0]
 $taskPins.Add("define_attribute {p:$taskPort} {PAP_IO_DIRECTION} {$($taskPin[2])}")
 $taskPins.Add("define_attribute {p:$taskPort} {PAP_IO_LOC} {$($taskPin[1])}")
 $taskPins.Add("define_attribute {p:$taskPort} {PAP_IO_VCCIO} {3.3}")
 $taskPins.Add("define_attribute {p:$taskPort} {PAP_IO_STANDARD} {LVCMOS33}")
 $taskPins.Add("define_attribute {p:$taskPort} {PAP_IO_NONE} {TRUE}")
}
$taskPins | Set-Content (Join-Path $taskConstraints 'board_pins.fdc') -Encoding utf8
# Purpose: reuse native DDR timing/placement with its required instance name.
(Get-Content (Join-Path $taskFpga 'constraints/ddr_native.fdc') -Raw).Replace('ref_clk_p','clk_p') |
 Set-Content (Join-Path $taskConstraints 'ddr_native.fdc') -Encoding utf8

# Purpose: scope the license override to this native PDS run and restore the
# caller environment afterward; no system-wide setting is changed.
$taskOldLicense=$env:PANGO_LICENSE_FILE
if($LicenseFile){$env:PANGO_LICENSE_FILE=(Resolve-Path -LiteralPath $LicenseFile).Path}
function Restore-DiagnosticLayout {
 # PDS saves "." after execution; normalize only this diagnostic project option.
 $taskText=Get-Content -LiteralPath $taskProject -Raw
 $taskOldOption='(_option prj_impl_dir (_string "."))'
 $taskNewOption='(_option prj_impl_dir (_string "../../build/mini_camera_diag/implementation"))'
 if($taskText.Contains($taskOldOption)){
  $taskText.Replace($taskOldOption,$taskNewOption) | Set-Content -LiteralPath $taskProject -Encoding utf8
 } elseif(!$taskText.Contains($taskNewOption)){throw 'Unexpected PDS implementation directory syntax'}
}
try {
 Push-Location $taskRun
 try {
  if($GenerateIps){
   foreach($taskName in @('afifo_16i_64o_512','afifo_64i_16o_128')){
    $taskIp=Join-Path $taskFpga "ip/mini_camera_diag/$taskName"
    # Preserve only the two copied/generated templates that native generation
    # refuses to overwrite; verify every exact source/destination stays in FPGA.
    $taskArchive=Join-Path $taskRun "templates/$taskName"
    New-Item -ItemType Directory -Path $taskArchive -Force | Out-Null
    foreach($taskExt in @('v','vhdl')){
     $taskTemplate=[IO.Path]::GetFullPath((Join-Path $taskIp "${taskName}_tmpl.$taskExt"))
     if(!$taskTemplate.StartsWith([IO.Path]::GetFullPath($taskIp)+[IO.Path]::DirectorySeparatorChar)){throw 'Unsafe template path'}
     if(Test-Path -LiteralPath $taskTemplate){Move-Item -LiteralPath $taskTemplate -Destination $taskArchive}
    }
    $taskOut=& "$PdsHome/bin/ip_generate.exe" -i (Join-Path $taskIp "$taskName.idf") -ads -disable-syn 2>&1
    $taskExit=$LASTEXITCODE
    $taskOut | Set-Content (Join-Path $taskRun "$taskName.log") -Encoding utf8
    if($taskExit -ne 0 -or ($taskOut -join "`n") -notmatch 'Done: 0 error\(s\), 0 warning\(s\)'){throw "IP generation failed: $taskName"}
    Write-Output "NATIVE_IP_PASS $taskName"
   }
  }
  # Purpose: generate .pds with the installed writer, then reopen that very file.
  $taskOut=& "$PdsHome/bin/pds_shell.exe" -file (Join-Path $PSScriptRoot 'create_mini_camera_diag.tcl') -work_dir $taskRun 2>&1
  $taskExit=$LASTEXITCODE
  $taskOut | Set-Content (Join-Path $taskRun 'generation.log') -Encoding utf8
  if($taskExit -ne 0 -or ($taskOut -join "`n") -match '(?m)^E:|Check license failed' -or
     ($taskOut -join "`n") -notmatch 'MINI_NATIVE_PROJECT_GENERATED'){throw 'Native project generation failed'}
  Restore-DiagnosticLayout
  $taskStarted=Get-Date
  $taskOut=& "$PdsHome/bin/pds_shell.exe" -project $taskProject -work_dir $taskImpl -run $Stage 2>&1
  $taskExit=$LASTEXITCODE
  $taskOut | Set-Content (Join-Path $taskRun "$Stage.log") -Encoding utf8
  Restore-DiagnosticLayout
  # Purpose: native exit is not sufficient; capture error lines and require a
  # fresh native stage report. No result here implies functional/timing sign-off.
  # Purpose: require a fresh native artifact for the requested terminal stage;
  # a successful process exit alone never authorizes hardware programming.
  $taskExt=@{compile='cmr';synthesize='snr';dev_map='dmr';pnr='prr';report_timing='rtr';gen_bit_stream='sbit'}[$Stage]
  $taskDir=@{compile='compile';synthesize='synthesize';dev_map='device_map';pnr='place_route';report_timing='report_timing';gen_bit_stream='generate_bitstream'}[$Stage]
  $taskReports=@(Get-ChildItem (Join-Path $taskImpl $taskDir) -Filter "*.$taskExt" -ErrorAction SilentlyContinue |
     Where-Object {$_.LastWriteTime -ge $taskStarted})
  $taskErrors=@($taskOut | Select-String '(?m)^E:|Check license failed')
  $taskBitstream=if($Stage -eq 'gen_bit_stream' -and $taskReports.Count -eq 1){$taskReports[0]}else{$null}
  $taskResult=[ordered]@{stage=$Stage;native_exit=$taskExit;error_count=$taskErrors.Count;
    fresh_reports=$taskReports.Count;native_stage_completed=($taskExit -eq 0 -and !$taskErrors.Count -and $taskReports.Count -gt 0);
    bitstream_sha256=if($taskBitstream){(Get-FileHash -LiteralPath $taskBitstream.FullName -Algorithm SHA256).Hash}else{$null};
    functional_verified=$false;external_timing_verified=$false;hardware_tested=$false;
    programmed=$false;download_allowed=$false;started=$taskStarted.ToString('o');finished=(Get-Date).ToString('o')}
  $taskResult | ConvertTo-Json | Set-Content (Join-Path $taskRun 'result.json') -Encoding utf8
  $taskResult | ConvertTo-Json
  Write-Output "Evidence: $taskRun"
  if(!$taskResult.native_stage_completed){$taskErrors.Line;throw 'Native stage incomplete; inspect retained evidence'}
  # Purpose: a completed report_timing action is not a timing pass. Abort on
  # violations/unknown summary wording while preserving all native stage evidence.
  if($Stage -in @('report_timing','gen_bit_stream')){ & (Join-Path $PSScriptRoot 'audit_mini_camera_timing.ps1') }
 } finally {Pop-Location}
} finally {$env:PANGO_LICENSE_FILE=$taskOldLicense}
