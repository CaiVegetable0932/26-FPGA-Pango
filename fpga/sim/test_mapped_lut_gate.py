"""Strict MAP-area gate boundaries; fixtures follow installed Fabric Compiler DMR."""
from pathlib import Path
import sys
import tempfile
import unittest
from types import SimpleNamespace
from unittest.mock import patch

SCRIPTS = Path(__file__).resolve().parents[1] / 'scripts'
sys.path.insert(0, str(SCRIPTS))
from implementation_readiness import read_mapped_resources, require_mapped_lut_budget


def native_report(used=46619, capacity=66600):
    """Include rounded 70% to prove admission uses the exact integer LUT count."""
    return ("Generated by Fabric Compiler ( version 2022.2-SP6.4 <build 146967> ) at fixture\n"
            "Device Utilization Summary:\n"
            "| Logic Utilization | Used | Available | Utilization(%)\n"
            f"| LUT | {used} | {capacity} | 70\n"
            "Device mapping done.\n")


class MappedLutGateTests(unittest.TestCase):
    """Over-budget/malformed evidence cannot be rescued by a readiness boolean."""
    def setUp(self):
        # Test-generated reports are FPGA build artifacts, never official files.
        root = Path(__file__).resolve().parents[1] / 'build/mcu_link_20261023/gate_tests'
        root.mkdir(parents=True, exist_ok=True)
        self.temp = tempfile.TemporaryDirectory(dir=root)
        self.addCleanup(self.temp.cleanup)
        self.build = Path(self.temp.name)
        self.report = self.build / 'device_map/pango_video_system.dmr'
        self.report.parent.mkdir()

    def write(self, text):
        """Publish an isolated fixture at the same path used by the native build."""
        self.report.write_text(text, encoding='utf-8')

    def test_exact_integer_below_threshold_passes_even_rounded_70(self):
        self.write(native_report(46619))
        result = require_mapped_lut_budget(self.build)
        self.assertEqual(result['total_lut'], 46619)
        self.assertTrue(result['below_70_percent'])
        self.assertEqual(len(result['report_sha256']), 64)

    def test_equal_or_above_threshold_refused(self):
        for used in (46620, 56804):
            with self.subTest(used=used):
                self.write(native_report(used))
                self.assertFalse(read_mapped_resources(self.build)['below_70_percent'])
                with self.assertRaisesRegex(ValueError, 'strictly below'):
                    require_mapped_lut_budget(self.build)

    def test_missing_invalid_and_partial_evidence_refused(self):
        with self.assertRaisesRegex(ValueError, 'Missing'):
            require_mapped_lut_budget(self.build)
        invalid = [native_report(capacity=100000), native_report(used='46,619'),
                   native_report().replace('Device mapping done.', ''),
                   native_report().replace('| LUT |', '| FF |'),
                   native_report().replace('Device mapping done.', '| LUT | 1 | 66600 | 1\nDevice mapping done.'),
                   native_report().replace('2022.2-SP6.4', '2021.3')]
        for text in invalid:
            with self.subTest(text=text):
                self.write(text)
                with self.assertRaises(ValueError):
                    require_mapped_lut_budget(self.build)

    def run_fresh_fixture(self, used, stage):
        """Execute the production phase dispatcher with only PDS replaced."""
        import build_video_system
        calls = []
        def fake_native(command, **kwargs):
            phase = command[command.index('-run')+1]
            calls.append(phase)
            kwargs['log_path'].write_text('fixture native stage complete\n')
            if phase == 'dev_map':
                self.write(native_report(used))
            return {'status': 'COMPLETED', 'returncode': 0}
        options = SimpleNamespace(stage=stage, overall_timeout_minutes=60, pause_file=None)
        with patch.object(build_video_system, 'run_supervised', side_effect=fake_native):
            result = build_video_system.run_native_candidate(self.build, 'fixture-shell', options, {})
        return calls, result

    def test_fresh_physical_entry_checks_map_before_dispatch(self):
        calls, result = self.run_fresh_fixture(46619, 'report_timing')
        self.assertEqual(calls, ['dev_map', 'report_timing'])
        self.assertIsNone(result[3])
        calls, result = self.run_fresh_fixture(46620, 'report_timing')
        self.assertEqual(calls, ['dev_map'])
        self.assertIn('strictly below', result[3])

    def test_dev_map_review_allows_over_budget_without_physical_run(self):
        calls, result = self.run_fresh_fixture(56804, 'dev_map')
        self.assertEqual(calls, ['dev_map'])
        self.assertIsNone(result[3])

    def test_resume_cannot_bypass_with_true_readiness(self):
        # Real resume CLI must fail before process discovery or PDS dispatch.
        # stop-after-timing is included; it does not relax area admission.
        import resume_video_system
        self.write(native_report(46620))
        (self.build / 'flow.pds').write_text('fixture')
        with patch.object(sys, 'argv', ['resume_video_system.py', '--build', str(self.build), '--stop-after-timing']), \
             patch.object(resume_video_system, 'require_whole_design_ready', return_value={}), \
             patch.object(resume_video_system.subprocess, 'run') as process_inventory, \
             patch.object(resume_video_system, 'run_supervised') as native:
            with self.assertRaisesRegex(ValueError, 'strictly below'):
                resume_video_system.main()
            process_inventory.assert_not_called()
            native.assert_not_called()


if __name__ == '__main__':
    unittest.main(verbosity=2)
