"""Final physical-area admission, using the installed Fabric Compiler PRR layout."""
from pathlib import Path
import sys
import tempfile
import unittest

FPGA = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FPGA / 'scripts'))
from implementation_readiness import read_routed_resources, require_routed_lut_budget


def native_report(total=46619, dram=1800):
    """Minimal native-shaped fixture; module LUT intentionally differs from area.

    Actual regional PRR has 1035+317 physical LUTs but 1351 module LUTs, so
    module figures must never override physical counts. Percentages are rounded.
    """
    return ("Generated by Fabric Compiler ( version 2022.2-SP6.4 <build 146967> ) at fixture\n"
            "Placement started.\nPlacement done.\nRouting started.\nRouting done.\n"
            "Device Utilization Summary :\n"
            "| Logic Utilization | Used | Available | Utilization(%)\n"
            "| Use of CLMA | 10000 | 11675 | 86\n"
            f"|   LUT | {total-10000} | 46700 | 79\n"
            "|   LUT-FF pairs | 12345 | 46700 | 27\n"
            "| Use of CLMS | 4000 | 4975 | 81\n"
            "|   LUT | 10000 | 19900 | 51\n"
            f"|   Distributed RAM | {dram} | 19900 | 10\n"
            "| Use of DRM | 80 | 155 | 52\n"
            "Device Utilization Summary Of Each Module:\n"
            "| Module Inst Name | LUT | FF | Distributed RAM\n"
            "| pango_video_system | 45555 | 12345 | 1800\n"
            "Inputs and Outputs :\n"
            "Flow Command: pnr -gplace_seed 13\n"
            "Total CPU time to pnr completion : 0h:1m:20s\n"
            "Process Total CPU time to pnr completion : 0h:1m:25s\n"
            "Total real time to pnr completion : 0h:2m:03s\n")


class RoutedLutGateTests(unittest.TestCase):
    """Only complete same-device route evidence can satisfy the strict budget."""
    def setUp(self):
        # All disposable evidence remains in the FPGA development area.
        root = FPGA / 'build/pose_storage_20261023/routed_gate_tests'
        root.mkdir(parents=True, exist_ok=True)
        self.temp = tempfile.TemporaryDirectory(dir=root)
        self.addCleanup(self.temp.cleanup)
        self.build = Path(self.temp.name)
        self.report = self.build / 'place_route/pango_video_system.prr'
        self.report.parent.mkdir()

    def write(self, text):
        """Create only the selected build's expected report, with Windows EOL."""
        self.report.write_bytes(text.replace('\n', '\r\n').encode('utf-8'))

    def test_strict_boundary_and_no_dram_double_count(self):
        self.write(native_report())
        result = require_routed_lut_budget(self.build)
        self.assertEqual(result['total_lut'], 46619)
        self.assertEqual(result['distributed_ram_lut'], 1800)
        self.assertEqual(result['clma_lut'] + result['clms_lut'], 46619)
        self.assertEqual(result['device_lut_capacity'], 66600)
        self.assertEqual(len(result['report_sha256']), 64)
        self.assertEqual(result['needed_reduction_for_strict_limit'], 0)
        for total in (46620, 46621, 55000):
            with self.subTest(total=total):
                self.write(native_report(total))
                self.assertEqual(read_routed_resources(self.build)['total_lut'], total)
                with self.assertRaisesRegex(ValueError, 'strictly below'):
                    require_routed_lut_budget(self.build)

    def test_missing_or_partial_report_is_not_evidence(self):
        with self.assertRaisesRegex(ValueError, 'Missing'):
            require_routed_lut_budget(self.build)
        for marker in ('Routing started.\n', 'Routing done.\n',
                       'Total real time to pnr completion : 0h:2m:03s\n',
                       '|   LUT | 10000 | 19900 | 51\n',
                       '|   Distributed RAM | 1800 | 19900 | 10\n'):
            with self.subTest(marker=marker):
                self.write(native_report().replace(marker, ''))
                with self.assertRaises(ValueError):
                    require_routed_lut_budget(self.build)

    def test_failed_or_place_only_run_refused_even_with_counts(self):
        for error in ('E: native route error', 'ERROR: internal failure',
                      'FATAL: database corrupt', 'Routing failed.', 'PnR aborted.'):
            with self.subTest(error=error):
                self.write(native_report().replace('Inputs and Outputs :', error + '\nInputs and Outputs :'))
                with self.assertRaisesRegex(ValueError, 'error'):
                    require_routed_lut_budget(self.build)
        self.write(native_report().replace('pnr -gplace_seed', 'pnr -place_only -gplace_seed'))
        with self.assertRaises(ValueError):
            require_routed_lut_budget(self.build)

    def test_wrong_device_version_or_integer_format_refused(self):
        for old, new in [('46700', '46701'), ('19900', '19901'),
                         ('2022.2-SP6.4', '2022.2-SP5'), ('build 146967', 'build 146968'),
                         ('36619', '36,619'), ('36619', '36619.0'), ('36619', '-1'),
                         ('| 79\n', '| 101\n'), ('| 36619 |', '| 99999 |')]:
            with self.subTest(old=old, new=new):
                self.write(native_report().replace(old, new))
                with self.assertRaises(ValueError):
                    require_routed_lut_budget(self.build)

    def test_ambiguous_or_misparented_rows_refused(self):
        for line in ('Device Utilization Summary :\n', 'Routing done.\n',
                     '| Use of CLMS | 4000 | 4975 | 81\n', '|   LUT | 10000 | 19900 | 51\n'):
            with self.subTest(line=line):
                self.write(native_report().replace(line, line + line))
                with self.assertRaises(ValueError):
                    require_routed_lut_budget(self.build)
        self.write(native_report().replace('Use of CLMS', 'Use of DRM'))
        with self.assertRaises(ValueError):
            require_routed_lut_budget(self.build)

    def test_dram_must_be_a_clms_subset(self):
        self.write(native_report(dram=10001))
        with self.assertRaisesRegex(ValueError, 'subset'):
            require_routed_lut_budget(self.build)

    def test_only_selected_whole_board_report_is_accepted(self):
        self.write(native_report().replace('| pango_video_system |', '| regional_wrapper |'))
        with self.assertRaisesRegex(ValueError, 'identity'):
            require_routed_lut_budget(self.build)

    def test_real_installed_report_layout(self):
        # Use actual completed PG2L100H tool output as a format regression.
        # Rename only fixture identity; this is not current board route evidence.
        source = FPGA / 'build/camera_input_20261012/pds/place_route/camera_input_bench.prr'
        text = source.read_text(encoding='utf-8')
        self.write(text.replace('camera_input_bench', 'pango_video_system'))
        result = require_routed_lut_budget(self.build)
        self.assertEqual(result['total_lut'], 511 + 256)
        self.assertEqual(result['distributed_ram_lut'], 0)


if __name__ == '__main__':
    unittest.main(verbosity=2)
