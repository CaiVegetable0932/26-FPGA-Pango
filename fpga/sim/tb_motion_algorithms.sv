  if(ps!=4 || pm!=manual)$fatal(1,"pose out-of-domain did not fall back");
  // Independent float64 evaluation of quantized calibration words at +1.5/-0.75
  // mechanical degrees exercises BOTH Jacobians, negative coefficients and all
  // six outputs. Values are not generated by the RTL's fixed-point arithmetic.
  reference_words[0]=67109;reference_words[1]=13422;reference_words[2]=-63753421;reference_words[3]=-6711;reference_words[4]=80531;reference_words[5]=-35567698;
