  expected[0]=67144;expected[1]=13361;expected[2]=-63533808;expected[3]=-6667;expected[4]=80566;expected[5]=-35796096;
  wait(ready);@(negedge clk);
  for(n=0;n<6;n=n+1)begin cal[384+n*32+:32]=reference_words[n];cal[576+n*32+:32]=pitch_words[n];cal[768+n*32+:32]=yaw_words[n];end
