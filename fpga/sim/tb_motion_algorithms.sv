  expected[0]=0;expected[1]=-335544;expected[2]=25165820;expected[3]=671089;expected[4]=0;expected[5]=6710879;
  @(negedge clk);cr=1;@(negedge clk);cr=0;wait(cv);#1;
  if(overflow)$fatal(1,"compose unexpected overflow");
  for(n=0;n<6;n=n+1)begin error=$signed(cm[n*32+:32])-expected[n];if(error< -32 || error>32)$fatal(1,"compose coefficient %d actual %d expected %d",n,$signed(cm[n*32+:32]),expected[n]);end
