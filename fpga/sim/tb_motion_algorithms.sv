  if(ps!=0)$fatal(1,"dual-axis pose rejected");
  for(n=0;n<6;n=n+1)begin error=$signed(pm[n*32+:32])-expected[n];if(error< -2 || error>2)$fatal(1,"pose coefficient %d error %d",n,error);end
