  .affine_enable(1'b1),.calibration(cal),.manual_matrix(manual),.epoch(64'd7),.frame_id(64'd99),
  .pose(pose),.pose_status(3'd0),.time_error_us(32'd100),.result_valid(pv),.result_ready(1'b1),
