  @(negedge clk);req=1;@(negedge clk);req=0;wait(pv);#1;
  if(ps!=0 || pe!=7 || pf!=99 || $signed(pm[64+:32])<1171269 || $signed(pm[64+:32])>1171273)$fatal(1,"pose radians/model mismatch status=%d value=%d",ps,$signed(pm[64+:32]));
