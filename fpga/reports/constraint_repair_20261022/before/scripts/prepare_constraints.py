"""Generate board pin inputs and adapt native DDR constraints in fpga only."""
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
board = json.loads((root / "config/board.json").read_text(encoding="utf-8"))
out = root / "constraints"
out.mkdir(exist_ok=True)

def expanded(mapping):
    for name, pins in mapping.items():
        if isinstance(pins, list):
            yield from ((f"{name}[{i}]", pin) for i, pin in enumerate(pins))
        else:
            yield name, pins

def attr(port, key, value):
    return f"define_attribute {{p:{port}}} {{{key}}} {{{value}}}\n"

seen = set()
ddr = "# Board manual V1.3 DDR pin map. Hardware validation pending.\n"
for port, pin in expanded(board["ddr_pins"]):
    if pin in seen: raise ValueError(f"Duplicate board pin {pin}")
    seen.add(pin)
    diff = port.startswith(("mem_dqs", "mem_ck")) and not port.startswith("mem_cke")
    direction = "INOUT" if port.startswith(("mem_dq", "mem_dqs")) else "OUTPUT"
    for key, value in dict(PAP_IO_LOC=pin, PAP_IO_DIRECTION=direction, PAP_IO_VCCIO="1.5",
                           PAP_IO_STANDARD="SSTL15D_I" if diff else "SSTL15_I",
                           PAP_IO_DRIVE="8.9", PAP_IO_SLEW="FAST").items():
        ddr += attr(port, key, value)
    if direction == "INOUT":
        for key, value in dict(PAP_IO_VREF_MODE="INT", PAP_IO_VREF_MODE_VALUE="0.5",
                               PAP_IO_DDR_TERM_MODE="ON", PAP_IO_DDR_RES="60", PAP_IO_CP_DYN_TERM="ON").items():
            ddr += attr(port, key, value)
(out / "ddr_board_pins.fdc").write_text(ddr, encoding="ascii")

pins = "# MINI board V1.3; no user or system settings are changed.\n"
for port, pin in expanded(board["pins"]):
    if pin in seen: raise ValueError(f"Duplicate board pin {pin}")
    seen.add(pin)
    standard = "TMDS" if port.startswith("hdmi_") else "SSTL15D_I" if port.startswith("ref_clk_") else "LVCMOS33"
    voltage = "1.5" if port.startswith("ref_clk_") else "3.3"
    direction = "INOUT" if port == "phy_mdio" else "INPUT" if port in ("clk_27m", "ref_clk_p", "ref_clk_n", "reset_n", "rgmii_rxc", "rgmii_rx_ctl") or port.startswith("rgmii_rxd") else "OUTPUT"
    pins += attr(port, "PAP_IO_DIRECTION", direction) + attr(port, "PAP_IO_LOC", pin)
    pins += attr(port, "PAP_IO_VCCIO", voltage) + attr(port, "PAP_IO_STANDARD", standard)
    pins += attr(port, "PAP_IO_NONE", "TRUE")
    if direction != "INPUT" and not port.startswith("hdmi_"):
        pins += attr(port, "PAP_IO_DRIVE", "4") + attr(port, "PAP_IO_SLEW", "SLOW" if port == "status_led" else "FAST")
(out / "board_pins.fdc").write_text(pins, encoding="ascii")

native = root / "ip/ddr3_controller/pnr/ddr_test.fdc"
if native.exists():
    content = native.read_text(encoding="utf-8")
    # PDS createFiles.tcl re-substitutes every imported IO LOC from its PAD_*
    # GUI enum values. Headless catalog defaults are NOT MINI board pins.
    # Retain native DDR timing/placement only, then supply our checked pin map.
    content = "\n".join(line for line in content.splitlines()
                        if "free_clk" not in line and not re.match(r"\s*define_attribute\s+\{p:", line)) + "\n"
    (out / "ddr_native.fdc").write_text(
        "# Native timing/placement only. Board pin authority is ddr_board_pins.fdc.\n" + content,
        encoding="utf-8")

# PDS 2022.2 keeps only one active RCF when add_constraint is called twice.
# Preserve both input files and concatenate their commands into one derived
# project-local RCF. Never change or overwrite the native IP RCF itself.
native_rcf = root / "ip/ddr3_controller/pnr/ddr3_controller.rcf"
if native_rcf.is_file():
    routing = "# Generated by prepare_constraints.py; edit the input constraints, not this file.\n"
    for source in (native_rcf, out / "hdmi_reset.rcf"):
        routing += f"# Source: {source.relative_to(root).as_posix()}\n"
        routing += source.read_text(encoding="utf-8").rstrip() + "\n"
    (out / "routing.rcf").write_text(routing, encoding="utf-8")
