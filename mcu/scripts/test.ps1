param([string]$Compiler='C:\MinGW\mingw64\bin\gcc.exe',[string]$BuildRoot='')
$ErrorActionPreference='Stop'
$mcuRoot=Split-Path -Parent $PSScriptRoot
Push-Location $mcuRoot
try {
    # Isolate local evidence from imported historical binaries. Explicit roots
    # are restricted to this MCU build area before any output is created.
    if (!$BuildRoot) {$BuildRoot=Join-Path $mcuRoot 'build/tests'}
    $testBuild=[IO.Path]::GetFullPath($BuildRoot)
    $allowedBuild=[IO.Path]::GetFullPath((Join-Path $mcuRoot 'build'))
    if (!$testBuild.StartsWith($allowedBuild+[IO.Path]::DirectorySeparatorChar,[StringComparison]::OrdinalIgnoreCase)) {throw 'BuildRoot must be inside mcu/build'}
    New-Item -ItemType Directory -Path $testBuild -Force | Out-Null
    function Check([string]$Name,[string[]]$Sources,[string[]]$Includes) {
        $exe=Join-Path $testBuild "$Name.exe"
        & $Compiler '-std=c11' '-O2' '-Wall' '-Wextra' '-Werror' @Includes @Sources '-lm' '-o' $exe
        if ($LASTEXITCODE) {throw "$Name compile failed"}
        & $exe
        if ($LASTEXITCODE) {throw "$Name failed"}
    }
    Check 'wire' @('tests/test_wire.c','firmware/common/wire.c') @('-Ifirmware/common')
    Check 'pose' @('tests/test_pose.c','firmware/common/pose.c') @('-Ifirmware/common')
    Check 'mpu6050' @('tests/test_mpu6050.c','firmware/common/wire.c','firmware/common/pose.c') @('-Itests/mpu_stubs','-Ifirmware/common','-Ifirmware/yuntai/Core/Inc')
    Check 'gateway' @('tests/test_gateway.c','firmware/common/wire.c') @('-Itests/gateway_stubs','-Ifirmware/common','-Ifirmware/longmenjia/Core/Inc')
    # The encoder profile oracle is emitted by the actual gateway builders.
    # Keep generated evidence separate and reject drift instead of rewriting it.
    & (Join-Path $testBuild 'gateway.exe') (Join-Path $testBuild 'encoder_vectors.json')
    if ($LASTEXITCODE) {throw 'Encoder gateway vector generation failed'}
    $encoderGenerated=(Get-Content (Join-Path $testBuild 'encoder_vectors.json') -Raw).Replace("`r",'')
    $encoderFixture=(Get-Content 'tests/encoder_vectors.json' -Raw).Replace("`r",'')
    if ($encoderGenerated -ne $encoderFixture) {throw 'Encoder gateway vectors differ from the checked fixture'}
    Check 'f1_link' @('tests/test_f1_link.c','firmware/common/wire.c','firmware/common/pose.c') @('-Itests/gateway_stubs','-Itests/f1_link_stubs','-Ifirmware/common','-Ifirmware/yuntai/Core/Inc')
    Check 'gimbal' @('tests/f1/test_gimbal.c','firmware/yuntai/Core/Src/gimbal_test.c') @('-Itests/f1/stubs','-Ifirmware/yuntai/Core/Inc')
    Check 'console' @('tests/f1/test_console.c','firmware/yuntai/Core/Src/host_console.c') @('-Itests/f1/stubs','-Ifirmware/yuntai/Core/Inc')
    Check 'servo' @('tests/f1/test_protocol.c','firmware/yuntai/Core/Src/uart_servo_lite.c','firmware/yuntai/Core/Src/ring_buffer.c') @('-Itests/f1/stubs','-Ifirmware/yuntai/Core/Inc')
    Check 'd36a' @('tests/f4/test_d36a_motor.c') @('-Itests/f4/mocks','-Ifirmware/longmenjia/Core/Inc')
    Check 'old_main' @('tests/f4/test_main_validation.c') @('-Itests/f4/mocks','-Ifirmware/longmenjia/Core/Inc')
    & $Compiler '-std=c11' '-Wall' '-Wextra' '-Werror' '-Ifirmware/common' 'tests/generate_vectors.c' 'firmware/common/wire.c' '-o' (Join-Path $testBuild 'generate_vectors.exe')
    if ($LASTEXITCODE) {throw 'Vector generator compilation failed'}
    & (Join-Path $testBuild 'generate_vectors.exe') (Join-Path $testBuild 'vectors.json')
    if ($LASTEXITCODE) {throw 'Vector generation failed'}
    # Independently generated bytes must match the repository's codec fixture;
    # do not silently rewrite an oracle while running a regression.
    $generated=(Get-Content (Join-Path $testBuild 'vectors.json') -Raw).Replace("`r",'')
    $fixture=(Get-Content 'tests/vectors.json' -Raw).Replace("`r",'')
    if ($generated -ne $fixture) {throw 'C-generated wire vectors differ from the checked fixture'}
    & python '-B' '../host/tests/test_mcu_pose_v2.py'
    if ($LASTEXITCODE) {throw 'Independent host decoder failed'}
} finally { Pop-Location }
